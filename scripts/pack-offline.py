"""Regenerate the public static offline pack after changing dist/."""
from pathlib import Path
import hashlib,json,re
root=Path(__file__).resolve().parents[1]/'dist'
files=sorted([p for p in root.iterdir() if p.name!='arena-worker.js' and p.suffix in {'.html','.css','.js','.svg'}])
# Pin the full ES module graph: a returning fan must never play a prior deck against a new rival target.
js=[p for p in files if p.suffix=='.js']
tag=hashlib.sha256(b''.join(p.name.encode()+p.read_bytes() for p in js)).hexdigest()[:12]
imports={'./'+p.name:'./'+p.name+'?r='+tag for p in js}
imports_script='<script type="importmap">'+json.dumps({'imports':imports},separators=(',',':'))+'</script>'
index=root/'index.html'
html=re.sub(r'<script type="importmap">.*?</script>','',index.read_text(),flags=re.S)
html=html.replace('</head>',imports_script+'</head>')
html=re.sub(r'src="app.js[^"]*"','src="app.js?r='+tag+'"',html)
index.write_text(html)
h=hashlib.sha256()
for p in files:
    h.update(p.name.encode()+b'\0'+p.read_bytes())
template="""// Generated by scripts/pack-offline.py. Public demo assets only.
const names=__FILES__, prefix='ot-matchday:'+self.registration.scope+':', version=prefix+'__VERSION__';
const base=self.registration.scope, urls=new Set(names.map(n=>new URL(n,base).href));
self.addEventListener('install',e=>e.waitUntil((async()=>{
  const cache=await caches.open(version);
  try{await cache.addAll([...urls].map(url=>new Request(url,{cache:'reload'})));}
  catch(err){await caches.delete(version);throw err;}
})()));
self.addEventListener('activate',e=>e.waitUntil((async()=>{
  for(const key of await caches.keys())if(key.startsWith(prefix)&&key!==version)await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch',e=>{
  if(e.request.method!=='GET')return;
  const u=new URL(e.request.url);u.search='';u.hash='';
  const shell=new URL('index.html',base).href, key=u.href===base?shell:u.href;
  if(!urls.has(key))return;
  e.respondWith((async()=>{const hit=await (await caches.open(version)).match(key);return hit||fetch(e.request);})());
});
"""
(root/'arena-worker.js').write_text(template.replace('__FILES__',json.dumps([p.name for p in files])).replace('__VERSION__',h.hexdigest()[:16]))
